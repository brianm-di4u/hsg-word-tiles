#!/usr/bin/env node
// Derives the tile set from the game dictionary (no commercial table is used or copied):
//   counts  letter frequency in playable words (2–8 letters, common words weighted ×3, a plural S
//           counted only when the singular is not also a word), scaled to 96 lettered tiles plus
//           2 blank "Steam" tiles. Every letter gets at least one tile.
//   values  1–10 from rarity (log of frequency) and from how few 2–3 letter words use the letter,
//           since short words are what make a letter easy to place, on a convex curve.
// Writes src/js/tiles.js and prints the table.
//   node tools/build-tiles.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadDict, words } from '../src/js/dict.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const d = await loadDict(fs.readFileSync(path.join(root, 'data/dict.b64.txt'), 'utf8'));
const all = [...words(d)];
const set = new Set(all);
const { isCommon } = await import('../src/js/dict.js');

const A = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
const freq = new Float64Array(26), short = new Float64Array(26);
let shortTotal = 0;
for (const w of all) {
  if (w.length <= 3) { shortTotal++; for (const ch of new Set(w)) short[ch.charCodeAt(0) - 65]++; }
  if (w.length < 2 || w.length > 8) continue;
  const plural = w.endsWith('S') && !w.endsWith('SS') && set.has(w.slice(0, -1));
  const weight = isCommon(d, w) ? 3 : 1;
  const letters = plural ? w.slice(0, -1) : w;
  for (const ch of letters) freq[ch.charCodeAt(0) - 65] += weight;
}
const sum = freq.reduce((a, b) => a + b, 0);
const f = [...freq].map((x) => x / sum);

// Counts: largest-remainder rounding to 96 with a floor of 1.
const LETTERED = 96, BLANKS = 2;
let counts = f.map((x) => Math.max(1, Math.floor(x * LETTERED)));
let left = LETTERED - counts.reduce((a, b) => a + b, 0);
const rema = f.map((x, i) => ({ i, r: x * LETTERED - counts[i] })).sort((a, b) => b.r - a.r);
for (let k = 0; left > 0; k++, left--) counts[rema[k % 26].i]++;
for (let k = 25; left < 0; k--) { const i = rema[k].i; if (counts[i] > 1) { counts[i]--; left++; } }

// Values: rarity + short-word scarcity, scaled so the rarest letter is 10 and the commonest 1.
const fmax = Math.max(...f);
const shortShare = [...short].map((x) => x / shortTotal);
const smax = Math.max(...shortShare);
const raw = f.map((x, i) => Math.log2(fmax / x) + 1.6 * (1 - shortShare[i] / smax));
const rmin = Math.min(...raw), rmax = Math.max(...raw);
// A convex curve keeps the common letters at 1–2 points and leaves the high values to the rare ones.
const CURVE = 1.7;
const values = raw.map((r) => Math.max(1, Math.min(10, Math.round(1 + 9 * ((r - rmin) / (rmax - rmin)) ** CURVE))));

const TILES = {};
for (let i = 0; i < 26; i++) TILES[A[i]] = { count: counts[i], value: values[i] };
const out = `// GENERATED by tools/build-tiles.mjs from the game dictionary – do not edit by hand.
// 96 lettered tiles and ${BLANKS} blank "Steam" tiles (value 0).
export const TILES = ${JSON.stringify(TILES)};
export const BLANKS = ${BLANKS};
export const TILE_TOTAL = ${LETTERED + BLANKS};
`;
fs.writeFileSync(path.join(root, 'src/js/tiles.js'), out);
console.log('letter  freq%  short%  count value');
for (let i = 0; i < 26; i++) console.log(`  ${A[i]}    ${(f[i] * 100).toFixed(2).padStart(5)}  ${(shortShare[i] * 100).toFixed(1).padStart(5)}   ${String(counts[i]).padStart(3)}   ${String(values[i]).padStart(3)}`);
const vowels = [...'AEIOU'].reduce((a, ch) => a + counts[ch.charCodeAt(0) - 65], 0);
console.log(`total ${counts.reduce((a, b) => a + b, 0)} lettered + ${BLANKS} blanks; vowels ${vowels}; face value ${counts.reduce((a, c, i) => a + c * values[i], 0)}`);
