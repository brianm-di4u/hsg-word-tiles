#!/usr/bin/env node
// Packs the painted art (art-src/art.json -> assets/*.webp via the shared art-pack tool), then writes
// src/js/art-list.js: the names the game may request. Only files that exist in assets/ are listed, so the
// game never asks for a missing image (a 404 would fail the harness).
//   node tools/build-art.mjs [--only a,b] [--allow-missing] [--list-only]
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ROOT = path.resolve(GAME);
const args = process.argv.slice(2);
if (!args.includes('--list-only')) {
  // Fail loudly on any art-pack error; callers must pass --allow-missing explicitly when raw PNGs are absent.
  execFileSync(process.execPath, [path.join(ROOT, 'shared', 'test-harness', 'art-pack.mjs'), '.', ...args], { cwd: ROOT, stdio: 'inherit' });
}
const manPath = path.join(GAME, 'assets', 'manifest.json');
const man = JSON.parse(fs.readFileSync(manPath, 'utf8'));
// the landmark vignettes are copied from Bathhouse Barons (same collection, MIT) rather than packed here: keep them
// listed with uniform { file, w, h, bytes, from } metadata
for (const f of fs.readdirSync(path.join(GAME, 'assets')).filter((f) => /^vig-.*\.webp$/.test(f)).sort()) {
  const n = f.slice(0, -5);
  const fp = path.join(GAME, 'assets', f);
  const prev = man[n] || {};
  man[n] = {
    file: f,
    w: prev.w || 320,
    h: prev.h || 320,
    bytes: fs.statSync(fp).size,
    from: prev.from || 'Bathhouse Barons (hsg-property-game, MIT)',
  };
}
fs.writeFileSync(manPath, JSON.stringify(man, null, 1) + '\n');
const spec = JSON.parse(fs.readFileSync(path.join(GAME, 'art-src', 'art.json'), 'utf8'));
const canvasSet = new Set((spec.items || []).filter((it) => it && it.canvas === true).map((it) => it.name));
const names = Object.keys(man).filter((n) => fs.existsSync(path.join(GAME, 'assets', n + '.webp')));

names.sort();
const canvasNames = names.filter((n) => canvasSet.has(n));
fs.writeFileSync(
  path.join(GAME, 'src', 'js', 'art-list.js'),
  `// GENERATED by tools/build-art.mjs from assets/manifest.json and art-src/art.json. Do not edit.\nexport const ART_LIST = ${JSON.stringify(names)};\nexport const CANVAS_ART = ${JSON.stringify(canvasNames)};\n`,
);
// file:// pages may draw local images into a 2D canvas, but WebGL refuses a canvas that holds them (it counts as
// tainted). Under file:// the game therefore loads ONLY canvas-rendered textures (CANVAS_ART) as data URLs.
const data = Object.fromEntries(canvasNames.map((n) => [n, 'data:image/webp;base64,' + fs.readFileSync(path.join(GAME, 'assets', n + '.webp')).toString('base64')]));
fs.writeFileSync(path.join(GAME, 'assets', 'art-data.js'), `/* GENERATED by tools/build-art.mjs: the packed canvas art as data URLs, loaded only when the game runs from file://. */
window.__ART_DATA = ${JSON.stringify(data)};
`);
const kb = names.reduce((a, n) => a + fs.statSync(path.join(GAME, 'assets', n + '.webp')).size, 0) / 1024;
const dataKb = fs.statSync(path.join(GAME, 'assets', 'art-data.js')).size / 1024;
console.log(`art-list.js: ${names.length} images (${canvasNames.length} canvas), ${kb.toFixed(0)} KB total, art-data.js ${dataKb.toFixed(1)} KB`);
