#!/usr/bin/env node
// Bundles the AI worker (src/js/worker-main.js and the rules, dictionary, move generator and AI it imports)
// into one classic script and writes it as a string to src/js/worker-src.js. The game starts the worker
// from a Blob URL, which works from file:// too. (The shared inliner drops <script> attributes, so the
// worker can't be read back from a tagged script block as Mahjong does.)
//   cd tools/dev && npm install   (once)
//   node tools/build-worker.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const here = path.dirname(fileURLToPath(import.meta.url));
const game = path.join(here, '..');
const esbuild = createRequire(path.join(here, 'dev', 'package.json'))('esbuild');
const res = await esbuild.build({
  entryPoints: [path.join(game, 'src', 'js', 'worker-main.js')],
  bundle: true, minify: true, format: 'iife', write: false, target: 'es2020', legalComments: 'none',
});
const code = res.outputFiles[0].text.trim();
fs.writeFileSync(path.join(game, 'src', 'js', 'worker-src.js'),
  `// GENERATED by tools/build-worker.mjs from src/js/worker-main.js – do not edit by hand.\nexport const WORKER_SRC = ${JSON.stringify(code)};\n`);
console.log(`worker-src.js ${(code.length / 1024).toFixed(1)} KB`);
