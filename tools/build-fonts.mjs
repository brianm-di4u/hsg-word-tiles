#!/usr/bin/env node
// Inlines the vendored OFL fonts (vendor/fonts/*.woff2, from npm @fontsource) into assets/fonts.css as data
// URIs (adapted from Bathhouse Barons). Chrome blocks @font-face file loads from file:// pages, so the fonts
// travel inside a stylesheet that a plain <link rel="stylesheet"> loads from file:// and http alike.
//   node tools/build-fonts.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const GAME = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SRC = path.join(GAME, 'vendor', 'fonts');
const FACES = [
  // title, screen headings, plaques: Art Deco display face (also the hsargames.com display face)
  ['Limelight', 400, 'normal', 'limelight-latin-400-normal.woff2'],
  // tile letters (800), headings and scores (600), fact cards (400 and italic)
  ['Fraunces', 400, 'normal', 'fraunces-latin-400-normal.woff2'],
  ['Fraunces', 400, 'italic', 'fraunces-latin-400-italic.woff2'],
  ['Fraunces', 600, 'normal', 'fraunces-latin-600-normal.woff2'],
  ['Fraunces', 800, 'normal', 'fraunces-latin-800-normal.woff2'],
  // interface text and buttons: geometric 1920s sans
  ['Josefin Sans', 400, 'normal', 'josefin-sans-latin-400-normal.woff2'],
  ['Josefin Sans', 600, 'normal', 'josefin-sans-latin-600-normal.woff2'],
  ['Josefin Sans', 700, 'normal', 'josefin-sans-latin-700-normal.woff2'],
];
let css = '/* Generated by tools/build-fonts.mjs from vendor/fonts (SIL Open Font License 1.1). Do not edit. */\n';
for (const [family, weight, style, file] of FACES) {
  const b64 = fs.readFileSync(path.join(SRC, file)).toString('base64');
  css += `@font-face{font-family:"${family}";font-style:${style};font-weight:${weight};font-display:block;` +
    `src:url(data:font/woff2;base64,${b64}) format("woff2")}\n`;
}
fs.mkdirSync(path.join(GAME, 'assets'), { recursive: true });
fs.writeFileSync(path.join(GAME, 'assets', 'fonts.css'), css);
console.log('assets/fonts.css', (css.length / 1024).toFixed(1), 'KB');
