#!/usr/bin/env node
// Builds the original 15×15 board for Bathhouse Letters and checks it.
//
// Theme: the valley's 47 hot springs. The centre "Display Spring" is where the first word goes; the
// other 46 springs are premium squares grouped in clusters (a word-premium core with letter premiums
// around it) that swirl out from the centre in a pinwheel, like water rising and spreading. The eight
// Bathhouse Row squares, one per historic bathhouse in north-to-south order, run clockwise round the edge.
//
// Every premium orbit below is listed once and turned through 90°, 180° and 270°, so the board has
// pinwheel symmetry; one extra pair of Warm squares on the centre row keeps the count at 46.
// Checks: 46 premiums + the Display Spring = 47; 180° symmetry; no two word premiums within 7 squares of
// each other on a line (no ×4/×6/×9 stacks inside one rack-length word); every square on the board.
// Writes src/js/layout.js.
//   node tools/build-layout.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const N = 15, C = 7;
const turn = ([r, c]) => [c, N - 1 - r];
const orbit = (rc) => { const out = [rc]; for (let k = 0; k < 3; k++) out.push(turn(out[out.length - 1])); return out; };

// kind: b = Boiling Spring (word ×3), s = Steam (word ×2), h = Hot (letter ×3), w = Warm (letter ×2)
const ORBITS = [
  ['b', [0, 4]],
  ['s', [2, 5]], ['s', [5, 1]], ['s', [4, 6]],
  ['h', [1, 3]], ['h', [5, 8]],
  ['w', [2, 3]], ['w', [1, 7]], ['w', [3, 5]], ['w', [4, 2]], ['w', [6, 3]],
];
const EXTRA = [['w', [7, 3]], ['w', [7, 11]]];
// Bathhouse Row, north to south (research/bathhouse-row-layout.md §1), placed clockwise from the top.
const ROW = ['Superior', 'Hale', 'Maurice', 'Fordyce', 'Quapaw', 'Ozark', 'Buckstaff', 'Lamar'];
const ROW_CELLS = [[0, 8], [1, 11], [8, 14], [11, 13], [14, 6], [13, 3], [6, 0], [3, 1]];

const grid = Array.from({ length: N }, () => Array(N).fill('.'));
const put = (k, [r, c]) => {
  if (r < 0 || c < 0 || r >= N || c >= N) throw new Error(`off the board: ${r},${c}`);
  if (grid[r][c] !== '.') throw new Error(`square ${r},${c} used twice (${grid[r][c]} and ${k})`);
  grid[r][c] = k;
};
put('*', [C, C]);
for (const [k, rc] of ORBITS) for (const cell of orbit(rc)) put(k, cell);
for (const [k, rc] of EXTRA) put(k, rc);
ROW_CELLS.forEach((rc) => put('B', rc));

// Checks
const cells = grid.flat();
const premiums = cells.filter((k) => 'bshw'.includes(k)).length;
const errors = [];
if (premiums + 1 !== 47) errors.push(`expected 46 premium squares, got ${premiums}`);
for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
  if (grid[r][c] !== grid[N - 1 - r][N - 1 - c]) errors.push(`not 180°-symmetric at ${r},${c}`);
}
const isWord = (k) => k === 'b' || k === 's';
for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
  if (!isWord(grid[r][c])) continue;
  for (let d = 1; d <= 7; d++) {
    if (c + d < N && isWord(grid[r][c + d])) errors.push(`word premiums ${d} apart on row ${r}`);
    if (r + d < N && isWord(grid[r + d][c])) errors.push(`word premiums ${d} apart on column ${c}`);
  }
}
if (errors.length) { console.error(errors.join('\n')); process.exit(1); }

const rows = grid.map((row) => row.join(''));
const bath = {};
ROW_CELLS.forEach(([r, c], i) => { bath[r * N + c] = ROW[i]; });
const count = (k) => cells.filter((x) => x === k).length;
fs.writeFileSync(path.join(root, 'src/js/layout.js'), `// GENERATED by tools/build-layout.mjs – do not edit by hand.
// . plain   w Warm (letter ×2)   h Hot (letter ×3)   s Steam (word ×2)   b Boiling Spring (word ×3)
// * Display Spring (the first word covers it)   B Bathhouse Row (doubles a bonus word's Hot Springs bonus)
export const SIZE = ${N};
export const CENTER = ${C * N + C};
export const ROWS = ${JSON.stringify(rows, null, 2)};
export const BATHHOUSES = ${JSON.stringify(bath)};
`);
console.log(rows.join('\n'));
console.log(`Boiling ${count('b')}  Steam ${count('s')}  Hot ${count('h')}  Warm ${count('w')}  = ${premiums} + Display Spring; Bathhouse Row ${count('B')}`);
